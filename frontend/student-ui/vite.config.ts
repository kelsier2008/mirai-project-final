import { defineConfig, loadEnv } from 'vite';
import react from '@vitejs/plugin-react';
import tailwindcss from '@tailwindcss/vite';

const DEFAULT_API = 'https://club-tracker-demo-api.onrender.com';

// Writes Cloudflare Pages `_headers` into dist/ with connect-src pinned to the configured
// API origin. Same policy as frontend/scripts/build-portal.mjs (student portal), minus the
// QR-code CDN this UI does not use.
function pagesHeaders(apiBase: string) {
  return {
    name: 'mirai-pages-headers',
    generateBundle(this: { emitFile: (f: { type: 'asset'; fileName: string; source: string }) => void }) {
      const origin = new URL(apiBase).origin;
      const csp = [
        "default-src 'self'",
        "script-src 'self'",
        "style-src 'self' 'unsafe-inline'",
        "img-src 'self' data: blob:",
        "font-src 'self' data:",
        `connect-src 'self' ${origin}`,
        'frame-src blob:',
        "object-src 'none'",
        "base-uri 'none'",
        "form-action 'self'",
        "frame-ancestors 'none'",
      ].join('; ');
      const source = `# Generated by vite.config.ts. Cloudflare Pages applies these headers to every response.
/*
  Content-Security-Policy: ${csp}
  X-Content-Type-Options: nosniff
  X-Frame-Options: DENY
  Referrer-Policy: strict-origin-when-cross-origin
  Cross-Origin-Opener-Policy: same-origin
  Permissions-Policy: camera=(self), geolocation=(self), microphone=(), payment=(), usb=()
`;
      this.emitFile({ type: 'asset', fileName: '_headers', source });
    },
  };
}

export default defineConfig(({ mode }) => {
  const env = loadEnv(mode, '.', 'VITE_');
  return {
    plugins: [react(), tailwindcss(), pagesHeaders(env.VITE_API_BASE_URL || DEFAULT_API)],
  };
});
